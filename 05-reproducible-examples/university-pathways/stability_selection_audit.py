"""Sensitivity audit for the fully synthetic university pathways example.

This script checks seed-to-seed variability and composition of the observed
semester panel. This is NOT a robustness check against alternative event
generating mechanisms, causal identification, or a bootstrap confidence
interval. It never creates empirical data or simulated psychological measures.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd
import statsmodels.api as sm
import statsmodels.formula.api as smf

from analysis import SEED, simulate

FORMULA = "credits_earned ~ semester + first_gen + preparation + support + C(campus)"
SEEDS = [SEED + j for j in range(10)]


def fit_gee(panel: pd.DataFrame) -> dict:
    fitted = smf.gee(
        FORMULA, groups="student_id", data=panel,
        family=sm.families.Gaussian(),
        cov_struct=sm.cov_struct.Exchangeable(),
    ).fit()
    return {
        "first_gen": float(fitted.params["first_gen"]),
        "semester": float(fitted.params["semester"]),
        "first_gen_se": float(fitted.bse["first_gen"]),
        "converged": bool(fitted.converged),
        "students": int(panel.student_id.nunique()),
        "observations": int(len(panel)),
    }


def panel_composition(students: pd.DataFrame, panel: pd.DataFrame) -> dict:
    enrolled = float(students.first_gen.mean())
    term1 = panel.loc[panel.semester == 1]
    late = panel.loc[panel.semester >= 9]
    withdrawals = students.loc[students.event == "withdrawal"]
    return {
        "entrants": int(len(students)),
        "term1_observed": int(term1.student_id.nunique()),
        "term9plus_observed_unique": int(late.student_id.nunique()),
        "term9plus_rows": int(len(late)),
        "never_observed_credits": int(len(students) - panel.student_id.nunique()),
        "entry_first_gen_proportion": enrolled,
        "term1_first_gen_proportion": float(term1.first_gen.mean()),
        "term9plus_first_gen_proportion_rows": float(late.first_gen.mean()),
        "withdrawal_proportion": float(len(withdrawals) / len(students)),
        "withdrawal_proportion_first_gen0": float(students.loc[students.first_gen == 0, "event"].eq("withdrawal").mean()),
        "withdrawal_proportion_first_gen1": float(students.loc[students.first_gen == 1, "event"].eq("withdrawal").mean()),
        "graduation_proportion": float(students.graduated.mean()),
        "note": "Term-9+ is an observed-semester composition, not a random sample of baseline entrants.",
    }


def run(seed_list=SEEDS) -> dict:
    iterations = []
    for seed in seed_list:
        students, panel = simulate(seed=seed)
        full = fit_gee(panel)
        early = fit_gee(panel.loc[panel.semester <= 6].copy())
        iterations.append({
            "seed": seed, "full_gee": full, "early_gee": early,
            "composition": panel_composition(students, panel),
            "first_gen_early_minus_full": early["first_gen"] - full["first_gen"],
        })
    x = np.array([i["full_gee"]["first_gen"] for i in iterations])
    delta = np.array([i["first_gen_early_minus_full"] for i in iterations])
    z = np.array([i["composition"]["term9plus_first_gen_proportion_rows"] - i["composition"]["entry_first_gen_proportion"] for i in iterations])
    result = {
        "metadata": {
            "synthetic": True, "base_seed": SEED, "seeds": list(seed_list),
            "type": "simulation sensitivity, not bootstrap or empirical replication",
            "formula": FORMULA,
            "full_panel_rule": "all recorded credit semesters until first graduation/withdrawal",
            "early_panel_rule": "recorded credit semesters 1 through 6",
        },
        "summary": {
            "first_gen_full_gee_min": float(x.min()),
            "first_gen_full_gee_max": float(x.max()),
            "first_gen_full_gee_mean": float(x.mean()),
            "first_gen_full_gee_sd_between_seeds": float(x.std(ddof=1)) if len(x)>1 else None,
            "early_minus_full_min": float(delta.min()),
            "early_minus_full_max": float(delta.max()),
            "mean_late_panel_first_gen_minus_entry": float(z.mean()),
            "n_converged_full": sum(i["full_gee"]["converged"] for i in iterations),
            "n_converged_early": sum(i["early_gee"]["converged"] for i in iterations),
        },
        "iterations": iterations,
        "interpretation_guards": [
            "All effects are generated by the same synthetic mechanism, with changed random seeds.",
            "Across-seed variability does not test alternative causal or observation-generating assumptions.",
            "Early-versus-full panels differ in time coverage and event-based selection; a contrast is not a pure selection-bias estimate.",
            "GEE working dependence does not make withdrawal or graduation ignorable.",
            "After withdrawal/graduation no actual semester-credit outcome is defined in the present simulator; do not impute these as observed counterfactuals.",
            "This does not assess LMM random-effect variance stability, which requires a separate targeted audit.",
        ],
    }
    return result


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--output", type=Path, default=Path("results/stability_selection_audit.json"))
    args = p.parse_args()
    report = run()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2, allow_nan=False) + "\n", encoding="utf-8")
    print(json.dumps({"summary": report["summary"],
                      "first_seed": report["iterations"][0]}, indent=2))


if __name__ == "__main__":
    main()
